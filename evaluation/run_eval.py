"""Evaluate BM25 retrieval on the labeled query set and write a Markdown report.

Usage:
    python -m evaluation.run_eval                       # chunk sizes 50, 100, 200
    python -m evaluation.run_eval --chunk-sizes 100 --out report.md

Everything except chunk size is held constant across runs: same corpus, queries,
tokenizer, BM25 parameters (k1=1.5, b=0.75) and metric definitions.
"""

import argparse
import json
import re
from collections import defaultdict
from dataclasses import dataclass
from pathlib import Path

from app.config import Settings
from app.ingestion.chunking import Chunk, normalize_text
from app.pipeline import DocumentService, SearchHit
from evaluation.corpus import load_corpus
from evaluation.metrics import mean, precision_at_k, recall_at_k, reciprocal_rank

DATA_DIR = Path(__file__).parent / "data"
DEFAULT_OUT = Path(__file__).parent / "results" / "report.md"
RECALL_KS = (1, 3, 5)
PRECISION_K = 5
RANK_DEPTH = 10  # MRR is computed over the top 10 results (MRR@10)
MIN_EVIDENCE_OVERLAP = 0.5  # fraction of evidence words a chunk must contain
WORD = re.compile(r"\S+")  # same word unit as the chunker


@dataclass
class QueryResult:
    query: dict
    hits: list[SearchHit]
    groups: list[set[str]]

    @property
    def ranked_ids(self) -> list[str]:
        return [h.chunk_id for h in self.hits]

    @property
    def first_relevant_rank(self) -> int | None:
        relevant = set().union(*self.groups) if self.groups else set()
        return next((i for i, cid in enumerate(self.ranked_ids, 1) if cid in relevant), None)


def load_queries(path: Path = DATA_DIR / "queries.json") -> list[dict]:
    return json.loads(path.read_text(encoding="utf-8"))["queries"]


def evidence_groups(query: dict, chunks_by_file: dict[str, list[Chunk]]) -> list[set[str]]:
    """Map each labeled evidence passage to the chunk IDs holding at least half of its words.

    Words, not characters: chunks split on word boundaries, so the separating space belongs
    to neither chunk and an evenly split passage would otherwise match no chunk at all.
    """
    groups = []
    for label in query["relevant"]:
        page_chunks = [c for c in chunks_by_file[label["filename"]] if c.page_number == label["page"]]
        # Chunks of a page joined by single spaces reproduce the normalized page text.
        page_text = " ".join(c.text for c in page_chunks)
        evidence = normalize_text(label["evidence"])
        start = page_text.find(evidence)
        if start < 0:
            raise ValueError(f"{query['id']}: evidence not found on {label['filename']} p{label['page']}")
        end = start + len(evidence)
        words = [m.span() for m in WORD.finditer(page_text) if m.start() < end and m.end() > start]
        group = {
            c.chunk_id
            for c in page_chunks
            if sum(c.char_start <= ws and we <= c.char_end for ws, we in words)
            >= MIN_EVIDENCE_OVERLAP * len(words)
        }
        if not group:
            raise ValueError(f"{query['id']}: no chunk holds half of the evidence; use a shorter span")
        groups.append(group)
    return groups


def build_service(chunk_size: int, corpus: dict[str, bytes]) -> tuple[DocumentService, dict[str, list[Chunk]]]:
    service = DocumentService(Settings(chunk_size_words=chunk_size))
    chunks_by_file = {}
    for filename, data in corpus.items():
        doc = service.ingest_pdf(filename, data)
        chunks_by_file[filename] = service.get_chunks(doc.document_id)
    return service, chunks_by_file


def evaluate(chunk_size: int, corpus: dict[str, bytes], queries: list[dict]) -> tuple[dict, list[QueryResult]]:
    service, chunks_by_file = build_service(chunk_size, corpus)
    results = [
        QueryResult(q, service.search(q["query"], top_k=RANK_DEPTH), evidence_groups(q, chunks_by_file))
        for q in queries
    ]
    answerable = [r for r in results if r.groups]
    summary = {
        "chunk_size": chunk_size,
        "chunks": sum(len(c) for c in chunks_by_file.values()),
        "answerable": len(answerable),
        **{f"recall@{k}": mean([recall_at_k(r.ranked_ids, r.groups, k) for r in answerable]) for k in RECALL_KS},
        f"precision@{PRECISION_K}": mean(
            [precision_at_k(r.ranked_ids, r.groups, PRECISION_K) for r in answerable]
        ),
        "mrr@10": mean([reciprocal_rank(r.ranked_ids, r.groups) for r in answerable]),
    }
    return summary, results


def metric_columns() -> list[str]:
    return [f"recall@{k}" for k in RECALL_KS] + [f"precision@{PRECISION_K}", "mrr@10"]


def render_report(summaries: list[dict], detail_size: int, detail: list[QueryResult]) -> str:
    cols = metric_columns()
    lines = [
        "# Retrieval evaluation report",
        "",
        "Generated by `python -m evaluation.run_eval`. Do not edit by hand.",
        "",
        f"- Queries: {len(detail)} ({summaries[0]['answerable']} answerable, "
        f"{len(detail) - summaries[0]['answerable']} no-answer)",
        "- Corpus: 3 original documents, 9 pages (`evaluation/data/corpus/`)",
        "- Retrieval: BM25 (k1=1.5, b=0.75, Lucene IDF), regex word tokenizer, no stemming",
        f"- Relevance: a chunk is relevant if it contains >= {MIN_EVIDENCE_OVERLAP:.0%} of the words "
        "of a labeled evidence passage",
        "- Metrics are averaged over answerable queries only",
        "",
        "## Chunk-size experiment",
        "",
        "| chunk size (words) | chunks | " + " | ".join(cols) + " |",
        "|---|---|" + "---|" * len(cols),
    ]
    for s in summaries:
        lines.append(f"| {s['chunk_size']} | {s['chunks']} | " + " | ".join(f"{s[c]:.3f}" for c in cols) + " |")

    by_type = defaultdict(list)
    for r in detail:
        if r.groups:
            by_type[r.query["type"]].append(r)
    lines += [
        "",
        f"## By query type (chunk size {detail_size})",
        "",
        "| type | n | recall@5 | mrr@10 |",
        "|---|---|---|---|",
    ]
    for qtype, rs in by_type.items():
        r5 = mean([recall_at_k(r.ranked_ids, r.groups, 5) for r in rs])
        mrr = mean([reciprocal_rank(r.ranked_ids, r.groups) for r in rs])
        lines.append(f"| {qtype} | {len(rs)} | {r5:.3f} | {mrr:.3f} |")

    lines += [
        "",
        f"## Per-query results (chunk size {detail_size})",
        "",
        "| id | type | query | first relevant rank | results | top hit |",
        "|---|---|---|---|---|---|",
    ]
    for r in detail:
        rank = "n/a" if not r.groups else (r.first_relevant_rank or "not in top 10")
        top = f"{r.hits[0].filename} p{r.hits[0].page_number} ({r.hits[0].score:.2f})" if r.hits else "-"
        lines.append(
            f"| {r.query['id']} | {r.query['type']} | {r.query['query']} | {rank} | {len(r.hits)} | {top} |"
        )
    lines.append("")
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--chunk-sizes", type=int, nargs="+", default=[50, 100, 200])
    parser.add_argument("--detail-size", type=int, default=Settings().chunk_size_words)
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT)
    args = parser.parse_args()

    corpus, queries = load_corpus(), load_queries()
    sizes = sorted(set(args.chunk_sizes) | {args.detail_size})
    runs = {size: evaluate(size, corpus, queries) for size in sizes}
    summaries = [runs[size][0] for size in sizes]

    report = render_report(summaries, args.detail_size, runs[args.detail_size][1])
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(report, encoding="utf-8")

    cols = metric_columns()
    print("size  chunks  " + "  ".join(f"{c:>12}" for c in cols))
    for s in summaries:
        print(f"{s['chunk_size']:>4}  {s['chunks']:>6}  " + "  ".join(f"{s[c]:>12.3f}" for c in cols))
    print(f"\nReport written to {args.out}")


if __name__ == "__main__":
    main()
